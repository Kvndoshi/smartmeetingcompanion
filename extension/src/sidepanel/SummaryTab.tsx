import { useEffect, useState } from "react";
import { api } from "../shared/api";
import { ext } from "../shared/ext";
import type { Meeting, MeetingSummary } from "../shared/protocol";
import { LANGUAGES } from "../utils/languages";

interface Props {
  meeting: Omit<Meeting, "segments"> | null;
  isLive: boolean;
  onMeetingChange: (m: Meeting) => void;
  onPatch: (patch: { summary_language?: string }) => Promise<void>;
}

function slugify(title: string): string {
  return (
    title
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "")
      .slice(0, 60) || "meeting"
  );
}

async function copyText(text: string): Promise<void> {
  try {
    await navigator.clipboard.writeText(text);
  } catch {
    const ta = document.createElement("textarea");
    ta.value = text;
    ta.style.position = "fixed";
    ta.style.opacity = "0";
    document.body.appendChild(ta);
    ta.select();
    document.execCommand("copy");
    ta.remove();
  }
}

function List({ title, items }: { title: string; items: string[] }) {
  if (!items?.length) return null;
  return (
    <section className="sum-section">
      <h3>{title}</h3>
      <ul>
        {items.map((item, i) => (
          <li key={i}>{item}</li>
        ))}
      </ul>
    </section>
  );
}

function SummaryView({ summary }: { summary: MeetingSummary }) {
  return (
    <div className="summary-view">
      {summary.overview && <p className="sum-overview">{summary.overview}</p>}
      <List title="Key points" items={summary.key_points} />
      <List title="Decisions" items={summary.decisions} />
      {summary.action_items?.length > 0 && (
        <section className="sum-section">
          <h3>Action items</h3>
          <ul className="action-items">
            {summary.action_items.map((a, i) => (
              <li key={i}>
                <span className="ai-task">{a.task}</span>
                {(a.owner || a.due) && (
                  <span className="ai-meta">
                    {a.owner && <span className="ai-owner">{a.owner}</span>}
                    {a.due && <span className="ai-due">due {a.due}</span>}
                  </span>
                )}
              </li>
            ))}
          </ul>
        </section>
      )}
      <List title="Open questions" items={summary.open_questions} />
      {summary.topics?.length > 0 && (
        <section className="sum-section">
          <h3>Topics</h3>
          <ul className="topics">
            {summary.topics.map((t, i) => (
              <li key={i}>
                {t.timestamp && <span className="seg-time">{t.timestamp}</span>} <b>{t.title}</b>
                {t.summary && <div className="topic-summary">{t.summary}</div>}
              </li>
            ))}
          </ul>
        </section>
      )}
      <List title="Next steps" items={summary.next_steps} />
      {summary._meta && (
        <div className="sum-meta">
          Generated by {summary._meta.provider} · {summary._meta.model} ·{" "}
          {new Date(summary._meta.generated_at * 1000).toLocaleString([], { dateStyle: "short", timeStyle: "short" })}
        </div>
      )}
    </div>
  );
}

const MEMORY_LABELS: Record<string, string> = {
  synced: "Saved to Supermemory",
  pending: "Waiting to sync to Supermemory",
  no_key: "Supermemory key not set — kept locally",
  error: "Supermemory sync failed",
  empty: "Nothing to save yet",
};

export default function SummaryTab({ meeting, isLive, onMeetingChange, onPatch }: Props) {
  const [language, setLanguage] = useState("en");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const [toast, setToast] = useState("");
  const [syncing, setSyncing] = useState(false);

  useEffect(() => {
    setError("");
    if (meeting?.summary_language) {
      setLanguage(meeting.summary_language);
      return;
    }
    void ext.storageGet<{ summaryLanguage: string }>(["summaryLanguage"]).then((d) => setLanguage(d.summaryLanguage || "en"));
  }, [meeting?.id]); // eslint-disable-line react-hooks/exhaustive-deps

  useEffect(() => {
    if (!toast) return;
    const id = setTimeout(() => setToast(""), 2000);
    return () => clearTimeout(id);
  }, [toast]);

  if (!meeting) {
    return (
      <div className="empty-state">
        <div className="empty-title">No meeting selected</div>
        <p>Pick a meeting from the Meetings tab to see its summary.</p>
      </div>
    );
  }

  const pending = meeting.summary_status === "pending" || busy;
  const summary = meeting.summary;

  const generate = async () => {
    setBusy(true);
    setError("");
    ext.storageSet({ summaryLanguage: language });
    try {
      const res = await api.summarize(meeting.id, language);
      onMeetingChange(res.meeting);
    } catch (err) {
      setError((err as Error).message);
    } finally {
      setBusy(false);
    }
  };

  const copyMarkdown = async () => {
    try {
      await copyText(await api.exportMarkdown(meeting.id, false));
      setToast("Copied summary as Markdown");
    } catch (err) {
      setError((err as Error).message);
    }
  };

  const download = async () => {
    try {
      const md = await api.exportMarkdown(meeting.id, true);
      const url = URL.createObjectURL(new Blob([md], { type: "text/markdown" }));
      const a = document.createElement("a");
      a.href = url;
      a.download = `${slugify(meeting.title)}.md`;
      a.click();
      setTimeout(() => URL.revokeObjectURL(url), 1000);
    } catch (err) {
      setError((err as Error).message);
    }
  };

  const syncMemory = async () => {
    setSyncing(true);
    try {
      const res = await api.syncMemory(meeting.id);
      onMeetingChange(res.meeting);
    } catch (err) {
      setError((err as Error).message);
    } finally {
      setSyncing(false);
    }
  };

  return (
    <div className="summary-tab">
      <div className="summary-controls">
        <select
          className="lang-select compact"
          value={language}
          onChange={(e) => {
            setLanguage(e.target.value);
            void onPatch({ summary_language: e.target.value });
          }}
          disabled={pending}
          aria-label="Summary language"
        >
          {LANGUAGES.map((l) => (
            <option key={l.code} value={l.code}>
              {l.name}
            </option>
          ))}
        </select>
        <button className="small-btn primary" type="button" onClick={generate} disabled={pending}>
          {pending ? "Summarizing…" : summary ? (isLive ? "Update summary" : "Regenerate") : isLive ? "Summarize so far" : "Generate summary"}
        </button>
      </div>

      {(error || (meeting.summary_status === "error" && meeting.summary_error)) && (
        <div className="inline-error">{error || meeting.summary_error}</div>
      )}

      {pending && !summary && <div className="loading-card">Reading the transcript and writing your notes…</div>}

      {summary ? (
        <>
          <div className="summary-title">{summary.title || meeting.title}</div>
          <SummaryView summary={summary} />
          <div className="summary-export">
            <button className="small-btn ghost" type="button" onClick={copyMarkdown}>
              Copy Markdown
            </button>
            <button className="small-btn ghost" type="button" onClick={download}>
              Download .md
            </button>
          </div>
        </>
      ) : (
        !pending && (
          <div className="empty-state">
            <p>
              {isLive
                ? "The summary is written automatically when the meeting ends — or generate one now."
                : "No summary yet. Generate one from the transcript."}
            </p>
          </div>
        )
      )}

      <div className="memory-status">
        <span className={`memory-dot ${meeting.memory_status || "none"}`} />
        <span>{MEMORY_LABELS[meeting.memory_status || ""] || "Not saved to Supermemory yet"}</span>
        {meeting.memory_status !== "synced" && (
          <button className="link-btn" type="button" onClick={syncMemory} disabled={syncing}>
            {syncing ? "Syncing…" : "Sync now"}
          </button>
        )}
        {meeting.memory_status === "error" && meeting.memory_error && (
          <div className="memory-error-detail">{meeting.memory_error}</div>
        )}
      </div>

      {toast && <div className="toast">{toast}</div>}
    </div>
  );
}
